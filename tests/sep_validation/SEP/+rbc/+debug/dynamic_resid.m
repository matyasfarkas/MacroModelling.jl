function [lhs, rhs] = dynamic_resid(y, x, params, steady_state)
T = NaN(13, 1);
lhs = NaN(7, 1);
rhs = NaN(7, 1);
T(1) = params(7)*exp(y(13));
T(2) = params(4)*y(1)^params(5)+(1-params(4))*y(10)^params(5);
T(3) = T(2)^(1/params(5));
T(4) = y(11)^params(2);
T(5) = (1-y(10))^(1-params(2));
T(6) = T(4)*T(5);
T(7) = T(6)^(1-params(3));
T(8) = y(18)^params(2);
T(9) = (1-y(17))^(1-params(2));
T(10) = T(8)*T(9);
T(11) = params(1)*T(10)^(1-params(3));
T(12) = T(11)/y(18);
T(13) = 1+params(4)*(y(16)/y(8))^(1-params(5))-params(6);
lhs(1) = y(13);
rhs(1) = params(8)*y(6)+params(9)*x(1);
lhs(2) = y(12);
rhs(2) = T(1);
lhs(3) = y(9);
rhs(3) = y(12)*T(3);
lhs(4) = y(8);
rhs(4) = y(9)-y(11)+y(1)*(1-params(6));
lhs(5) = y(11)*(1-params(2))/params(2)/(1-y(10))-(1-params(4))*(y(9)/y(10))^(1-params(5));
rhs(5) = 0;
lhs(6) = T(7)/y(11);
rhs(6) = T(12)*T(13);
lhs(7) = y(14);
rhs(7) = y(9)-y(11);
end
